def build_negative_spec(manifest: dict) -> dict:
    """The negative regression spec: ONLY the legacy string locator
    `Capacity` (duplicated 3× in column B) with field_label_column: B on both
    sides — must fail AMBIGUOUS, never first-match."""
    spec = build_spec(manifest, (4, 5))
    spec["task"]["intent"] = "negative: duplicated legacy label must fail"
    spec["mapping"]["targets"][0]["matrix"]["field_map"] = [
        {"source": "Capacity", "target": "Capacity"}]
    spec["validation"]["key_outputs"] = []
    return spec


