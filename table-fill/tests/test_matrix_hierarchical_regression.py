"""Ticket 02 (P0-02) — Hierarchical Matrix Canonical Regression: full-chain E2E.

Replays the REAL hierarchical parameter-sheet shape through the whole Runtime
seam — Prepare (real officecli flatten with merged-parent propagation) → Matrix
FillSpec (all three locator forms mixed) → Compile → Execute → Structural Gate
(draft_receipt) → Semantic Gate (final workbook scan) — plus the negative
regression that locks "first match wins" can never come back.

Fixture: tests/_fixtures/hierarchical_matrix/ (data-neutral canonical asset,
checked-in xlsx generated by the dev-time generate_fixtures.py — the test
COPIES the checked-in workbooks into a temp workdir and NEVER imports the
generator). Structure (see the generator docstring):

  source_parameter_book.xlsx (sheet Params, internal-facing):
    - A = Section with REAL vertical merges (Cooling A3:A6, Heating A7:A9) —
      flatten propagates the anchor into every child row's A cell;
    - B = Parameter (duplicated: Capacity ×3, EER/Operation/COP/Sound/Supply);
    - C = Unit — the final disambiguator (Btu/h vs W);
    - D/E/F = records (12K/18K/24K tokens), data-neutral values;
    - Operation row carries the sanctioned controlled source value
      "Heating pump" → target "Cooling and Heating" (spec D9 example variant —
      see generator docstring for why the controlled vocabulary is ASCII);
    - Supply row carries padded " 220 " values → trim → "220";
    - Internal | Cost Code | USD | 内部成本×3 = internal-only row: present in
      the source, absent in the target, unmapped by field_map — must never
      reach the final workbook.

  target_template.xlsx (sheet Template, customer-facing): same field rows
  minus the internal row (rows offset by +1 due to the note row — locators
  must not depend on absolute row equality between sides).

Hard acceptance (all must hold simultaneously):
  - Matrix compile PASS (exit 0, no defects);
  - A/B/C target schema writes = 0 (every plan write column ⊆ {D,E,F});
  - 100% source lineage: |source_trace| == |writes|, write paths == trace
    paths, every entry exactly {target, source, transform_chain};
  - zero BULK_SOURCE_DERIVED_LITERAL_FALLBACK warning; zero
    MATRIX_FIELD_LOCATOR_AMBIGUOUS;
  - Structural Gate PASS (draft_receipt.json) AND Semantic Gate PASS (exit 0);
  - internal-only values absent from the final workbook (zip/XML scan);
  - data-neutrality self-check (forbidden tokens absent from fixtures, flat
    CSVs, produced JSON and the final workbook).

Negative regression: the same fixture with a bad spec — field_map contains
ONLY the legacy string locator `source: Capacity` / `target: Capacity` with
`field_label_column: B` declared on both sides (Capacity lives in column B and
appears 3×) → compile MUST FAIL, exit 3, FIRST defect code
MATRIX_FIELD_LOCATOR_AMBIGUOUS, and MATRIX_FIELD_LOCATOR_NOT_FOUND must NOT be
present. Asserted via the CLI (authoritative) and in-process (compile_spec).

Known environment fact (KNOWN_TRAPS · Office concurrency and officecli 1.0.145
mechanics): officecli batch can transiently fail (~1/4 BATCH_CHUNK_FAILED) and
its get/batch JSON returns non-ASCII as XML numeric character references; the
execute step is retried ONCE on BATCH_CHUNK_FAILED (documented product recovery
path), and the controlled vocabulary is ASCII by design (see the generator).

Run:
  python -m pytest table-fill/tests/test_matrix_hierarchical_regression.py -q
"""

