    def _data_neutrality(self, draft: Path, manifest: dict) -> None:
        """Forbidden real-customer tokens must never appear in the checked-in
        fixtures, the flattened CSVs, the produced JSON/MD or the final
        workbook (raw or entity-escaped)."""
        texts = []
        for path in (SRC_XLSX, TGT_XLSX, draft):
            texts.append((path.name, zip_text(path)))
        for p in sorted(self.workdir.glob("*.csv")):
            texts.append((p.name, p.read_text(encoding="utf-8-sig")))
        for name in ("fill_spec.yaml", "prepare_manifest.json",
                     "execution_plan.json", "mapping.md", "source_trace.json",
                     "draft_receipt.json", "semantic_policy.json",
                     "semantic_receipt.json", "mod_resolution.json"):
            p = self.workdir / name
            if p.is_file():
                texts.append((name, p.read_text(encoding="utf-8")))
        for label, text in texts:
            for token in FORBIDDEN_TOKENS:
                self.assertNotIn(token, text,
                                 f"forbidden token {token!r} in {label}")

    def test_negative_regression_legacy_duplicate_label_ambiguous(self):
        """Same fixture, bad spec: ONLY `source: Capacity` (legacy string,
        field_label_column: B, Capacity ×3) → compile MUST fail with exit 3 and
        MATRIX_FIELD_LOCATOR_AMBIGUOUS; NOT_FOUND must not appear. The CLI is
        the authoritative seam; an in-process compile_spec assertion rides
        along (cheap)."""
        wd = self.workdir
        manifest = self._prepare()
        self._verify_flat_contract(manifest)
        (wd / "mod_resolution.json").write_text(
            json.dumps(mod_record(self.mods), ensure_ascii=False),
            encoding="utf-8")
        spec = build_negative_spec(manifest)
        (wd / "fill_spec_negative.yaml").write_text(
            yaml.safe_dump(spec, allow_unicode=True, sort_keys=False),
            encoding="utf-8")

        # CLI (authoritative)
        proc = run_py(wd, "compile_fill.py", "--spec", "fill_spec_negative.yaml",
                      "--workdir", ".")
        self.assertEqual(proc.returncode, 3,
                         f"expected exit 3, got {proc.returncode}: "
                         f"{proc.stdout} {proc.stderr}")
        self.assertIn("MATRIX_FIELD_LOCATOR_AMBIGUOUS", proc.stderr)
        self.assertNotIn("MATRIX_FIELD_LOCATOR_NOT_FOUND", proc.stderr)
        payload = json.loads(proc.stderr)
        codes = [d["code"] for d in payload["defects"]]
        self.assertIn("MATRIX_FIELD_LOCATOR_AMBIGUOUS", codes)
        self.assertNotIn("MATRIX_FIELD_LOCATOR_NOT_FOUND", codes)
        # first / fully AMBIGUOUS: both sides resolve the duplicated label
        self.assertTrue(all(c == "MATRIX_FIELD_LOCATOR_AMBIGUOUS"
                            for c in codes), codes)
        # a failing compile must not produce a plan
        self.assertFalse((wd / "execution_plan.json").exists())

        # In-process (same compiler entry the CLI uses)
        if str(SCRIPTS) not in sys.path:
            sys.path.insert(0, str(SCRIPTS))
        import compile_fill  # noqa: PLC0415
        from io import StringIO  # noqa: PLC0415
        buf = StringIO()
        old = sys.stderr
        sys.stderr = buf
        try:
            with self.assertRaises(SystemExit) as cm:
                compile_fill.compile_spec(spec, manifest, wd)
            self.assertEqual(cm.exception.code, 3)
        finally:
            sys.stderr = old
        inner = json.loads(buf.getvalue())
        inner_codes = [d["code"] for d in inner["defects"]]
        self.assertIn("MATRIX_FIELD_LOCATOR_AMBIGUOUS", inner_codes)
        self.assertNotIn("MATRIX_FIELD_LOCATOR_NOT_FOUND", inner_codes)


