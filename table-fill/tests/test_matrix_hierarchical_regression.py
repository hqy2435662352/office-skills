def load_flat_rows(workdir: Path, name: str) -> list[tuple[list[str], int]]:
    """Read a flattened CSV (utf-8-sig) into [(values, orig_row), ...]."""
    rows = []
    with open(workdir / f"{name}_flat.csv", encoding="utf-8-sig",
              newline="") as fh:
        for line in csv.reader(fh):
            if not line:
                continue
            try:
                orig = int(line[-1].strip())
            except (ValueError, IndexError):
                continue
            rows.append((line[:-1], orig))
    return rows


def zip_text(path: Path) -> str:
    """Every zip part of a workbook, XML-entity-unescaped (catches both raw
    and escaped leakage — officecli stores non-ASCII as numeric char refs)."""
    with zipfile.ZipFile(path) as z:
        return _html.unescape("".join(
            z.read(n).decode("utf-8", errors="replace")
            for n in z.namelist()))


def file_sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def mod_record(mods_copy: Path) -> dict:
    """MOD Adjudication Record locked to the param_sheet MOD (canonical
    path/revision/sha256) — consumed by BOTH compile (C1–C3) and the semantic
    gate (canonical resolver)."""
    sha = file_sha256(mods_copy / "MOD_param.md")
    return {
        "status": "resolved", "selected": "param_sheet",
        "selected_revision": 1,
        "selected_canonical_path": "MOD_param.md",
        "selected_sha256": sha,
        "candidates": [{"name": "param_sheet",
                        "canonical_path": "MOD_param.md",
                        "revision": 1, "sha256": sha}],
    }


